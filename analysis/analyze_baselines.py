#!/usr/bin/env python3
"""
Extended-baseline comparison (Reviewer 1.5 / 2.4).

Reads the resilient ledger (results/experiment_ledger.csv) for the baseline
sweep — FedAgain vs. FedAvg / FedProx / FedMedian / Bulyan / FedBN / Scaffold /
MOON — under non-IID label skew, 30% corrupted clients, severity 3, seeds
42/43/44, on {A (Daudon), B (Jonathan), C (MyStone), CIFAR-10}.

Outputs:
  results/baselines/baseline_table.tex   -- table* ready to paste (blue-coded)
  results/baselines/baseline_summary.csv -- machine-readable mean/std
  results/baselines/baseline_comparison.png (+ copy into src-paper/)

Honest framing: best value per dataset is bolded regardless of method.
"""
import csv
import os
import statistics as st
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEDGER = os.path.join(ROOT, "results", "experiment_ledger.csv")
OUTDIR = os.path.join(ROOT, "results", "baselines")
SRCPAPER = os.path.join(ROOT, "jcr-fedagain", "src-paper")
os.makedirs(OUTDIR, exist_ok=True)

# Sweep selectors
DATASETS = ["DAUDON_MIX", "JONATHAN_MIX", "MYSTONE", "CIFAR10"]
DS_LABEL = {
    "DAUDON_MIX": "A (Daudon)",
    "JONATHAN_MIX": "B (Jonathan)",
    "MYSTONE": "C (MyStone)",
    "CIFAR10": "CIFAR-10",
}
STRATS = ["FedAvg", "FedProx", "FedMedian", "Bulyan",
          "FedBN", "Scaffold", "MOON", "FedDyn", "RFLPA", "BOBA", "FedAgain"]
CR, SEV, DIST = "0.3", "3", "non-iid-label"


def load():
    agg = defaultdict(lambda: defaultdict(lambda: {"acc": [], "f1": []}))
    with open(LEDGER) as f:
        for r in csv.DictReader(f):
            if (r["status"] == "completed" and r["dataset"] in DATASETS
                    and r["corrupt_ratio"] == CR and r["corruption_severity"] == SEV
                    and r["data_distribution"] == DIST and r["strategy"] in STRATS
                    # keep only the canonical image-corruption runs: exclude the
                    # label-flip poisoning sweep and the epsilon-sensitivity sweep
                    and "pm-" not in r["run_key"] and "_eps" not in r["run_key"]):
                agg[r["dataset"]][r["strategy"]]["acc"].append(float(r["final_accuracy"]) * 100)
                agg[r["dataset"]][r["strategy"]]["f1"].append(float(r["final_f1"]) * 100)
    return agg


def stats(vals):
    m = st.mean(vals)
    s = st.pstdev(vals) if len(vals) > 1 else 0.0
    return m, s


def main():
    agg = load()

    # summary per (dataset, strategy)
    summary = {}  # (ds, strat) -> (acc_m, acc_s, f1_m, f1_s, n)
    for ds in DATASETS:
        for s in STRATS:
            v = agg[ds].get(s)
            if not v or not v["acc"]:
                continue
            am, asd = stats(v["acc"])
            fm, fsd = stats(v["f1"])
            summary[(ds, s)] = (am, asd, fm, fsd, len(v["acc"]))

    # best accuracy per dataset (for bolding)
    best_acc = {ds: max((summary[(ds, s)][0] for s in STRATS if (ds, s) in summary), default=None)
                for ds in DATASETS}
    best_f1 = {ds: max((summary[(ds, s)][2] for s in STRATS if (ds, s) in summary), default=None)
               for ds in DATASETS}

    # ---- CSV ----
    with open(os.path.join(OUTDIR, "baseline_summary.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["dataset", "strategy", "acc_mean", "acc_std", "f1_mean", "f1_std", "n"])
        for ds in DATASETS:
            for s in STRATS:
                if (ds, s) in summary:
                    am, asd, fm, fsd, n = summary[(ds, s)]
                    w.writerow([ds, s, f"{am:.2f}", f"{asd:.2f}", f"{fm:.2f}", f"{fsd:.2f}", n])

    # ---- average accuracy & mean rank (honest overall summary) ----
    print("\n=== Overall summary (mean over 4 datasets) ===")
    avg = {}
    for s in STRATS:
        accs = [summary[(ds, s)][0] for ds in DATASETS if (ds, s) in summary]
        if len(accs) == len(DATASETS):
            avg[s] = st.mean(accs)
    # mean rank
    ranks = defaultdict(list)
    for ds in DATASETS:
        ordered = sorted([s for s in STRATS if (ds, s) in summary],
                         key=lambda s: -summary[(ds, s)][0])
        for i, s in enumerate(ordered, 1):
            ranks[s].append(i)
    for s in sorted(avg, key=lambda k: -avg[k]):
        mr = st.mean(ranks[s]) if ranks[s] else float("nan")
        print(f"  {s:<10} avg_acc={avg[s]:6.2f}   mean_rank={mr:.2f}")

    # ---- LaTeX table* ----
    def cell(val, std, is_best):
        body = f"{val:.2f}\\,$\\pm$\\,{std:.2f}"
        return f"\\textbf{{{body}}}" if is_best else body

    lines = []
    lines.append("% Auto-generated by analysis/analyze_baselines.py  (R1.5 / R2.4 -> blue)")
    lines.append("\\begin{table*}[t]")
    lines.append("\\centering")
    lines.append("{\\color{blue}")
    lines.append("\\caption{Extended baseline comparison under non-IID label skew with 30\\% "
                 "corrupted clients (severity~3), averaged over three seeds (42/43/44). "
                 "Each cell reports mean accuracy\\,$\\pm$\\,standard deviation (\\%); the best "
                 "value per dataset is shown in bold. FedAgain is the only method that ranks "
                 "in the top two on every dataset and attains the best result on CIFAR-10, while "
                 "outperforming all personalization- and drift-correction baselines (FedBN, MOON, "
                 "Scaffold) on the clinical datasets. FedMedian is competitive but discards half of "
                 "the client updates coordinate-wise and, like Bulyan, presupposes knowledge of the "
                 "number of corrupted clients.\\label{tab:baseline_comparison}}")
    ncol = "l" + "c" * len(DATASETS)
    lines.append(f"\\begin{{tabular}}{{{ncol}}}")
    lines.append("\\hline")
    header = "\\textbf{Strategy} & " + " & ".join(f"\\textbf{{{DS_LABEL[ds]}}}" for ds in DATASETS) + " \\\\"
    lines.append(header)
    lines.append("\\hline")
    for s in STRATS:
        name = f"\\textbf{{{s}}}" if s == "FedAgain" else s
        cells = []
        for ds in DATASETS:
            if (ds, s) in summary:
                am, asd, _, _, _ = summary[(ds, s)]
                cells.append(cell(am, asd, abs(am - best_acc[ds]) < 1e-9))
            else:
                cells.append("--")
        row = name + " & " + " & ".join(cells) + " \\\\"
        if s == "FedAgain":
            lines.append("\\hline")
        lines.append(row)
    lines.append("\\hline")
    lines.append("\\end{tabular}")
    lines.append("}")
    lines.append("\\end{table*}")
    tex = "\n".join(lines) + "\n"
    with open(os.path.join(OUTDIR, "baseline_table.tex"), "w") as f:
        f.write(tex)
    print("\n=== LaTeX table written to results/baselines/baseline_table.tex ===\n")
    print(tex)

    # ---- grouped-bar figure (accuracy) ----
    plt.rcParams.update({"font.size": 15})
    fig, ax = plt.subplots(figsize=(13, 5.2))
    x = np.arange(len(DATASETS))
    w = 0.078
    # colorblind-safe-ish; FedAgain highlighted red
    palette = {
        "FedAvg": "#7f7f7f", "FedProx": "#8c9eb5", "FedMedian": "#1f77b4",
        "Bulyan": "#2ca02c", "FedBN": "#9467bd", "Scaffold": "#ff9e4a",
        "MOON": "#8c564b", "FedDyn": "#bcbd22", "RFLPA": "#17becf",
        "BOBA": "#e377c2", "FedAgain": "#d62728",
    }
    for i, s in enumerate(STRATS):
        means = [summary[(ds, s)][0] if (ds, s) in summary else 0 for ds in DATASETS]
        errs = [summary[(ds, s)][1] if (ds, s) in summary else 0 for ds in DATASETS]
        off = (i - (len(STRATS) - 1) / 2) * w
        ax.bar(x + off, means, w, yerr=errs, capsize=2, label=s,
               color=palette[s], edgecolor="black" if s == "FedAgain" else "none",
               linewidth=1.4 if s == "FedAgain" else 0)
    ax.set_xticks(x)
    ax.set_xticklabels([DS_LABEL[d] for d in DATASETS])
    ax.set_ylabel("Test accuracy (\\%)" if plt.rcParams["text.usetex"] else "Test accuracy (%)")
    # 0-based: FedDyn (MyStone) and BOBA (CIFAR-10, subspace degeneracy) fall
    # far below the 45% floor used before the R2.4 baselines were added.
    ax.set_ylim(0, 95)
    ax.grid(axis="y", ls=":", alpha=0.5)
    ax.legend(ncol=4, loc="upper center", bbox_to_anchor=(0.5, 1.16), frameon=False, fontsize=13)
    fig.tight_layout()
    out = os.path.join(OUTDIR, "baseline_comparison.png")
    fig.savefig(out, dpi=200, bbox_inches="tight")
    if os.path.isdir(SRCPAPER):
        import shutil
        shutil.copy(out, os.path.join(SRCPAPER, "baseline_comparison.png"))
        print(f"Figure copied to src-paper/baseline_comparison.png")
    print(f"Figure written to {out}")


if __name__ == "__main__":
    main()
